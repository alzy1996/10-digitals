#!/usr/bin/env node
/**
 * Writes src/engine/fontCoverage.js: the code points the two bundled 3D sign fonts can draw
 * (src/assets/fonts/readex-latin-600.woff and readex-arabic-600.woff), as compact [start, end] ranges.
 *
 * Why: troika-three-text looks up any character the sign fonts lack with its unicode-font-resolver, and that
 * resolver retries on a third-party CDN when our own URL has no data. The engine therefore never hands troika a
 * character outside these ranges (src/engine/textGuard.js), and tools/validate-venue.mjs refuses venue text
 * that uses one. Run this again whenever the font files change:   node tools/font-coverage.mjs
 * (tests/fonts.test.js fails when the generated file and the fonts disagree).
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_FONTS_DIR, readWoffCodepoints } from './validate-venue.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(ROOT, 'src/engine/fontCoverage.js')

/** Sorted code points -> [[start, end], ...] */
export function toRanges(set) {
  const cps = [...set].sort((a, b) => a - b)
  const out = []
  for (const c of cps) {
    const last = out[out.length - 1]
    if (last && c === last[1] + 1) last[1] = c
    else out.push([c, c])
  }
  return out
}

export function coverageRanges(fontsDir = DEFAULT_FONTS_DIR) {
  return {
    latin: toRanges(readWoffCodepoints(resolve(fontsDir, 'readex-latin-600.woff'))),
    arabic: toRanges(readWoffCodepoints(resolve(fontsDir, 'readex-arabic-600.woff'))),
  }
}

export function renderModule({ latin, arabic }) {
  const fmt = (ranges) => `[${ranges.map(([a, b]) => `[${a}, ${b}]`).join(', ')}]`
  return `/**
 * GENERATED by tools/font-coverage.mjs from src/assets/fonts/*.woff. Do not edit by hand.
 * Code points each 3D sign font can draw, as inclusive [start, end] ranges (see src/engine/textGuard.js).
 */
export const LATIN_RANGES = ${fmt(latin)}
export const ARABIC_RANGES = ${fmt(arabic)}
`
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  const cov = coverageRanges()
  writeFileSync(OUT, renderModule(cov))
  const count = (r) => r.reduce((s, [a, b]) => s + b - a + 1, 0)
  console.log(`wrote src/engine/fontCoverage.js · Latin ${count(cov.latin)} code points · Arabic ${count(cov.arabic)} code points`)
}
